create function bruff_private.chat_normalize(t text) returns text language sql immutable set search_path='' as $$
 select ' '||btrim(regexp_replace(lower(translate(t,'ÁÉÍÓÚÜÑáéíóúüñ','AEIOUUNaeiouun')),'[^a-z0-9]+',' ','g'))||' ';
$$;
create function public.bruff_chat_status(w uuid) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare r text; e uuid;
begin
 select role into r from bruff_private.memberships where workspace_id=w and user_id=auth.uid() and status='active';
 if r is null or not exists(select 1 from auth.users where id=auth.uid() and email_confirmed_at is not null) then raise exception 'Acceso no permitido' using errcode='42501';end if;
 if r<>'owner' then select event_id into e from bruff_private.chat_safety_blocks where workspace_id=w and user_id=auth.uid();end if;
 return jsonb_build_object('blocked',e is not null,'event_id',e);
end $$;
create function public.bruff_chat_screen(w uuid,c uuid,fan text,body text) returns jsonb language plpgsql security definer set search_path='' as $$
declare m bruff_private.memberships; hits jsonb; e uuid; normalized text; model text;
begin
 select * into m from bruff_private.memberships where workspace_id=w and user_id=auth.uid() for update;
 if not found or m.status<>'active' or not bruff_private.can_access(w,c,'send') or not exists(select 1 from auth.users where id=auth.uid() and email_confirmed_at is not null)
 then raise exception 'Acceso no permitido' using errcode='42501';end if;
 if m.role<>'owner' then select event_id into e from bruff_private.chat_safety_blocks where workspace_id=w and user_id=auth.uid();end if;
 if e is not null then return jsonb_build_object('allowed',false,'blocked',true,'event_id',e);end if;
 if fan is null or fan !~ '^[0-9]{1,24}$' or body is null or length(body)>10000 then raise exception 'Mensaje inválido';end if;
 normalized:=bruff_private.chat_normalize(body);
 select jsonb_agg(jsonb_build_object('term',term,'category',category) order by category,term) into hits from bruff_private.chat_safety_terms where position(bruff_private.chat_normalize(term) in normalized)>0;
 if hits is null then return jsonb_build_object('allowed',true,'blocked',false);end if;
 select display_name into model from bruff_private.creator_accounts where workspace_id=w and id=c;
 select id into e from bruff_private.chat_safety_events where workspace_id=w and actor_id=auth.uid() and creator_id=c and fan_id=fan and md5(message_text)=md5(body) and reviewed_at is null;
 if e is null then
 insert into bruff_private.chat_safety_events(workspace_id,actor_id,creator_id,actor_name,actor_role,model_name,fan_id,message_text,matches)
 values(w,auth.uid(),c,m.display_name,m.role,model,fan,body,hits) returning id into e;
 end if;
 if m.role<>'owner' then insert into bruff_private.chat_safety_blocks(workspace_id,user_id,event_id) values(w,auth.uid(),e) on conflict(workspace_id,user_id) do update set event_id=excluded.event_id,blocked_at=now();end if;
 return jsonb_build_object('allowed',false,'blocked',m.role<>'owner','event_id',e,'matches',hits);
end $$;
create function public.bruff_chat_incidents(w uuid,before_time timestamptz default null,before_id uuid default null) returns jsonb language plpgsql stable security definer set search_path='' as $$
begin
 if not exists(select 1 from bruff_private.memberships m join auth.users u on u.id=m.user_id where m.workspace_id=w and m.user_id=auth.uid() and m.role='owner' and m.status='active' and u.email_confirmed_at is not null) then raise exception 'Solo propietario' using errcode='42501';end if;
 return jsonb_build_object('blocked',coalesce((select jsonb_agg(to_jsonb(b)) from bruff_private.chat_safety_blocks b where workspace_id=w),'[]'::jsonb),
 'pending', (select count(*) from bruff_private.chat_safety_events where workspace_id=w and reviewed_at is null),
 'events',coalesce((select jsonb_agg(to_jsonb(e) order by e.created_at desc,e.id desc) from
 (select * from bruff_private.chat_safety_events where workspace_id=w and (before_time is null or (created_at,id)<(before_time,before_id)) order by created_at desc,id desc limit 50)e),'[]'::jsonb));
end $$;
create function public.bruff_chat_release(w uuid,event uuid,note text) returns void language plpgsql security definer set search_path='' as $$
declare e bruff_private.chat_safety_events;
begin
 if not exists(select 1 from bruff_private.memberships m join auth.users u on u.id=m.user_id where m.workspace_id=w and m.user_id=auth.uid() and m.role='owner' and m.status='active' and u.email_confirmed_at is not null) then raise exception 'Solo propietario' using errcode='42501';end if;
 if note is null or length(btrim(note)) not between 3 and 1000 then raise exception 'Indica el motivo de la revisión';end if;
 select * into e from bruff_private.chat_safety_events where workspace_id=w and id=event;
 if not found then raise exception 'Aviso no encontrado';end if;
 perform 1 from bruff_private.memberships where workspace_id=w and user_id=e.actor_id for update;
 update bruff_private.chat_safety_events set reviewed_at=now(),reviewed_by=auth.uid(),review_note=btrim(note) where workspace_id=w and id=event and reviewed_at is null;
 if not found then raise exception 'Aviso ya revisado';end if;
 delete from bruff_private.chat_safety_blocks where workspace_id=w and user_id=e.actor_id and event_id=event;
 insert into bruff_private.team_audit(workspace_id,actor_id,action,target_id) values(w,auth.uid(),'chat_safety_reviewed',e.actor_id);
end $$;
