create table bruff_private.chat_safety_events(
 id uuid primary key default gen_random_uuid(),workspace_id uuid not null,actor_id uuid not null,creator_id uuid not null,
 actor_name text,actor_role text not null,model_name text not null,fan_id text not null,
 message_text text not null check(length(message_text)<=10000),matches jsonb not null,policy_version text not null default 'bruff-strict-1',
 created_at timestamptz not null default now(),reviewed_at timestamptz,reviewed_by uuid,review_note text,
 foreign key(workspace_id,actor_id) references bruff_private.memberships(workspace_id,user_id),
 foreign key(workspace_id,creator_id) references bruff_private.creator_accounts(workspace_id,id)
);
create index chat_safety_events_workspace on bruff_private.chat_safety_events(workspace_id,created_at desc,id);
create unique index chat_safety_unreviewed_duplicate on bruff_private.chat_safety_events(workspace_id,actor_id,creator_id,fan_id,md5(message_text)) where reviewed_at is null;
create table bruff_private.chat_safety_blocks(
 workspace_id uuid not null,user_id uuid not null,event_id uuid not null references bruff_private.chat_safety_events(id),blocked_at timestamptz not null default now(),
 primary key(workspace_id,user_id),foreign key(workspace_id,user_id) references bruff_private.memberships(workspace_id,user_id)
);
alter table bruff_private.chat_safety_terms enable row level security;
alter table bruff_private.chat_safety_events enable row level security;
alter table bruff_private.chat_safety_blocks enable row level security;
